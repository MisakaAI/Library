# 工资计算

基本工资 = 10000
各项补贴 = 503

工资 = 基本工资 + 各项补贴

# 五险个人承担比例：养老8%，医疗2%，失业0.5%，合计10.5%
五险个人比例 = 0.08 + 0.02 + 0.005
五险 = 工资 * 五险个人比例

# 住房公积金个人部分（固定400元）
住房公积金 = 400

# 未考虑专项附加扣除的应纳税所得额
应纳税所得额 = 工资 - 五险 - 住房公积金 - 5000

# 计算个税函数
def 计算个税(应纳税所得额):
    if 应纳税所得额 <= 0:
        return 0
    elif 应纳税所得额 <= 3000:
        return 应纳税所得额 * 0.03
    elif 应纳税所得额 <= 12000:
        return 应纳税所得额 * 0.10 - 210
    elif 应纳税所得额 <= 25000:
        return 应纳税所得额 * 0.20 - 1410
    elif 应纳税所得额 <= 35000:
        return 应纳税所得额 * 0.25 - 2660
    elif 应纳税所得额 <= 55000:
        return 应纳税所得额 * 0.30 - 4410
    elif 应纳税所得额 <= 80000:
        return 应纳税所得额 * 0.35 - 7160
    else:
        return 应纳税所得额 * 0.45 - 15160

个税 = 计算个税(应纳税所得额)

# 专项附加扣除
专项附加扣除 = 1000 + 3000
实际应纳税所得额 = 应纳税所得额 - 专项附加扣除
实际个税 = 计算个税(实际应纳税所得额)

全年已预缴个税 = 个税 * 12
全年实际应缴个税 = 实际个税 * 12
应退税额 = 全年已预缴个税 - 全年实际应缴个税

实发工资 = 工资 - 五险 - 住房公积金 - 个税

# ========== 企业支出部分（完善） ==========

# 企业五险缴纳比例（青岛市西海岸新区）
企业养老比例 = 0.16
企业医疗比例 = 0.085   # 含生育保险
企业失业比例 = 0.007
企业工伤比例 = 0.007   # 一类行业基准费率，实际按行业浮动

企业五险比例 = 企业养老比例 + 企业医疗比例 + 企业失业比例 + 企业工伤比例
# = 0.16 + 0.085 + 0.007 + 0.007 = 0.259

企业五险 = 工资 * 企业五险比例

# 住房公积金企业部分（与个人一致，固定400元）
企业住房公积金 = 400

# 企业实际支出 = 应发工资 + 企业五险 + 企业住房公积金
企业实际支出 = 工资 + 企业五险 + 企业住房公积金

